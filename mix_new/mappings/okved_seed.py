"""Стартовая (НЕполная) таблица соответствий ТН ВЭД/ОКПД2 -> ОКВЭД.

Это не официальный полный перечень соответствий ФТС/Росстандарта — такие
таблицы велики и многие-ко-многим. Здесь — курируемый минимум для кодов,
типично относящихся к опту и производству, который нужно пополнять по
мере обработки реальных актов. См. okved_seed.md."""
from __future__ import annotations

import re

TNVED_TO_OKVED: dict[str, list[str]] = {
    "7208": ["24.10", "46.72"],  # прокат плоский из железа/стали — металлургия/опт металлов
    "7210": ["24.10", "46.72"],
    "8471": ["26.20", "46.51"],  # вычислительные машины — производство/опт техники
    "8542": ["26.11", "46.52"],  # электронные интегральные схемы
    "3004": ["21.20", "46.46"],  # лекарственные средства
    "1001": ["01.11", "46.21"],  # пшеница — опт сельхозпродукции
    "2710": ["19.20", "46.71"],  # нефтепродукты
}

OKPD2_TO_OKVED: dict[str, list[str]] = {
    "10": ["10", "46.3"],  # продукты питания
    "20": ["20", "46.75"],  # химическая продукция
    "24": ["24", "46.72"],  # металлургия
    "26": ["26", "46.5"],  # компьютеры, электроника
    "28": ["28", "46.6"],  # машины и оборудование
}

COMMODITY_GROUP_KEYWORDS: dict[str, list[str]] = {
    "продукты питания": ["пищев", "продовольств"],
    "стройматериалы": ["строительн", "цемент", "кирпич"],
    "металлопродукция": ["металлопрокат", "металлург", "сталь", "чугун"],
    "лекарственные средства": ["лекарств", "фармацевт"],
    "сельхозпродукция": ["сельскохозяйствен", "зерно", "удобрен"],
    "химическая продукция": ["химическ", "реагент"],
}


def lookup_by_code(code: str) -> list[str]:
    """Пробует ТН ВЭД, затем ОКПД2, по возрастающей длине префикса."""
    code = code.strip()
    for table in (TNVED_TO_OKVED, OKPD2_TO_OKVED):
        for length in range(min(len(code), 10), 1, -1):
            prefix = code[:length]
            if prefix in table:
                return table[prefix]
    return []


def lookup_by_keyword(text: str) -> tuple[list[str], list[str]]:
    """Возвращает (товарные_группы, okved-коды — пока пусто, т.к. по ключевым
    словам мы определяем только товарную группу, не прямой код)."""
    lowered = text.lower()
    groups = []
    for group_name, keywords in COMMODITY_GROUP_KEYWORDS.items():
        if any(re.search(kw, lowered) for kw in keywords):
            groups.append(group_name)
    return groups, []
